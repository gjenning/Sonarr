#!/usr/bin/env bash
# Session handoff: picks the next actionable task (IN_PROGRESS, else first TODO with all
# dependencies DONE) and writes HANDOFF.md so a fresh session can resume with zero archaeology.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/HANDOFF.md"

declare -A STATUS TITLE FILE
ids=()
for f in "$ROOT"/phase-*/task-*.md; do
  [ -e "$f" ] || continue
  id="$(basename "$f" | sed -E 's/^task-([0-9]+)-([0-9]+).*$/\1.\2/')"
  ids+=("$id")
  STATUS[$id]="$(grep -m1 '^Status:' "$f" | sed 's/^Status:[[:space:]]*//')"
  TITLE[$id]="$(grep -m1 '^# ' "$f" | sed -E 's/^#+[[:space:]]*//; s/^Task [0-9.]+:[[:space:]]*//')"
  FILE[$id]="$f"
done

next=""
for id in "${ids[@]}"; do
  [[ "${STATUS[$id]}" == IN_PROGRESS ]] && { next=$id; break; }
done
if [[ -z "$next" ]]; then
  for id in "${ids[@]}"; do
    [[ "${STATUS[$id]}" != TODO ]] && continue
    deps="$(grep -m1 '^Depends:' "${FILE[$id]}" | sed 's/^Depends:[[:space:]]*//')"
    ok=1
    IFS=',' read -ra arr <<< "$deps"
    for d in "${arr[@]}"; do
      d="$(echo "$d" | tr -d ' -')"
      [[ -z "$d" ]] && continue
      [[ "${STATUS[$d]:-DONE}" == DONE ]] || ok=0
    done
    [[ $ok -eq 1 ]] && { next=$id; break; }
  done
fi

done_count=0; total=${#ids[@]}
remaining=""
for id in "${ids[@]}"; do
  if [[ "${STATUS[$id]}" == DONE ]]; then done_count=$((done_count+1)); else
    remaining+="| ${id} | ${TITLE[$id]} | ${STATUS[$id]} |"$'\n'
  fi
done

{
  echo "# Handoff — Custom Audio Formats"
  echo
  echo "_Generated by scripts/handoff.sh · $(date '+%Y-%m-%d %H:%M') · ${done_count}/${total} tasks done_"
  echo
  if [[ -z "$next" ]]; then
    echo "**All actionable tasks are DONE or BLOCKED.** Run \`scripts/status.sh\` to inspect."
  else
    echo "**Next task: ${next} — ${TITLE[$next]#Task }**"
    echo "File: \`${FILE[$next]#"$ROOT"/}\`"
    echo
    echo "---"
    echo
    cat "${FILE[$next]}"
  fi
  echo
  echo "## Remaining tasks"
  echo
  echo "| ID | Task | Status |"
  echo "|----|------|--------|"
  printf '%s' "$remaining"
  echo
  echo "## Resume protocol"
  echo
  echo "See \`.planning/README.md\` → Task lifecycle. Read \`.planning/00-overview.md\` once for design context."
} > "$OUT"

cat "$OUT"
