#!/usr/bin/env bash
# Progress dashboard: parses Status lines from all task files → STATUS.md
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/STATUS.md"

declare -A COUNTS=([TODO]=0 [IN_PROGRESS]=0 [BLOCKED]=0 [DONE]=0)
rows=""

for f in "$ROOT"/phase-*/task-*.md; do
  [ -e "$f" ] || continue
  id="$(basename "$f" | sed -E 's/^task-([0-9]+)-([0-9]+).*$/\1.\2/')"
  title="$(grep -m1 '^# ' "$f" | sed -E 's/^#+[[:space:]]*//; s/^Task [0-9.]+:[[:space:]]*//')"
  status="$(grep -m1 '^Status:' "$f" | sed 's/^Status:[[:space:]]*//')"
  if [[ -n "${COUNTS[$status]+x}" ]]; then COUNTS[$status]=$(( ${COUNTS[$status]} + 1 )); fi
  rows+="| ${id} | ${title} | ${status} | ${f#"$ROOT"/} |"$'\n'
done

{
  echo "# Status — Custom Audio Formats"
  echo
  echo "_Generated by scripts/status.sh · $(date '+%Y-%m-%d %H:%M')_"
  echo
  echo "**Done ${COUNTS[DONE]} · In progress ${COUNTS[IN_PROGRESS]} · Blocked ${COUNTS[BLOCKED]} · Todo ${COUNTS[TODO]}**"
  echo
  echo "| ID | Task | Status | File |"
  echo "|----|------|--------|------|"
  printf '%s' "$rows"
} > "$OUT"

cat "$OUT"
